#!/usr/bin/env node
// =============================================================================
// build-dua-share-pages.js  (v224)
// =============================================================================
// WHAT IT DOES
//   Reads data/duas/metadata.json and writes one tiny static page per Dua,
//   Ziyarat and Amal to d/<id>.html. Each page carries that item's own Open
//   Graph / Twitter tags (title, short meaning, source) so a WhatsApp /
//   Facebook / Telegram link preview shows the right item, and it sends a
//   visitor straight into the app:  ../?page=dua&open=<type>:<id>
//   content-links.js (loaded by index.html) turns that into "open this item".
//   Also keeps a marked block in sitemap.xml up to date (re-running replaces
//   the block, never duplicates it). Same idea as tools/build-share-pages.js
//   (blog posts, p/<id>.html); the two do not touch each other's files.
//
// WHEN TO RUN  (Node only, no packages)
//   node tools/build-dua-share-pages.js           write / refresh d/*.html + sitemap block
//   node tools/build-dua-share-pages.js --check   change nothing; exit 1 if out of date
//   node tools/build-dua-share-pages.js --base=https://example.org/path/
//   Run it after adding or editing duas / ziyarat / amal, then commit d/ and
//   sitemap.xml together with data/duas/metadata.json.
// =============================================================================
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DEFAULT_BASE = 'https://ahlalbayt313.github.io/The-Role-of-Ahl-al-Bayt-a.s/';
const SITE_NAME = 'আহলে বাইত (আ.) | Ahl al-Bayt (a.s)';
const OUT_DIR = path.join(ROOT, 'd');
const SITEMAP = path.join(ROOT, 'sitemap.xml');
const MARK_START = '<!-- dua-share-pages:start (generated by tools/build-dua-share-pages.js — do not edit) -->';
const MARK_END = '<!-- dua-share-pages:end -->';
const TYPES = [['duas', 'dua', 'দোয়া'], ['ziyarats', 'ziyarat', 'যিয়ারত'], ['amals', 'amal', 'আমল']];

const args = process.argv.slice(2);
const CHECK = args.indexOf('--check') > -1;
let base = process.env.SITE_BASE || DEFAULT_BASE;
args.forEach(a => { if (a.indexOf('--base=') === 0) base = a.slice(7); });
if (!/^https?:\/\//.test(base)) { console.error('Base address must start with http:// or https://'); process.exit(2); }
if (base.slice(-1) !== '/') base += '/';

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const oneLine = s => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
const clip = (s, n) => { const a = Array.from(s); return a.length > n ? a.slice(0, n - 1).join('').trim() + '…' : s; };

function pageFor(type, label, it) {
    const id = String(it.id);
    const title = oneLine(it.titleBn) || oneLine(it.titleEn) || label;
    const bits = [oneLine(it.occasion), oneLine(it.meaningBn), oneLine(it.source) ? 'সূত্র: ' + oneLine(it.source) : ''].filter(Boolean);
    const desc = clip(bits.join(' — ') || oneLine(it.titleEn) || title, 200);
    const url = base + 'd/' + id + '.html';
    const img = base + 'og-image.jpg';
    const target = '../?page=dua&open=' + type + ':' + id;
    return [
        '<!DOCTYPE html>', '<html lang="bn">', '<head>', '<meta charset="UTF-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<title>' + esc(title) + ' | ' + label + ' | আহলে বাইত (আ.)</title>',
        '<meta name="description" content="' + esc(desc) + '">',
        '<link rel="canonical" href="' + esc(url) + '">',
        '<link rel="icon" href="../favicon.ico">',
        '<meta property="og:type" content="article">',
        '<meta property="og:site_name" content="' + esc(SITE_NAME) + '">',
        '<meta property="og:title" content="' + esc(title) + '">',
        '<meta property="og:description" content="' + esc(desc) + '">',
        '<meta property="og:url" content="' + esc(url) + '">',
        '<meta property="og:image" content="' + esc(img) + '">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        '<meta property="og:locale" content="bn_BD">',
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="' + esc(title) + '">',
        '<meta name="twitter:description" content="' + esc(desc) + '">',
        '<meta name="twitter:image" content="' + esc(img) + '">',
        '<meta http-equiv="refresh" content="0;url=' + esc(target) + '">',
        '<script>location.replace("' + target + '" + location.hash);</script>',
        '</head>', '<body>', '<article>',
        '<h1>' + esc(title) + '</h1>', '<p>' + esc(desc) + '</p>',
        '<p><a href="' + esc(target) + '">অ্যাপে পুরোটা পড়ুন →</a></p>',
        '</article>', '</body>', '</html>', ''
    ].join('\n');
}
const rx = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
function withSitemapBlock(xml, items) {
    const out = [MARK_START];
    items.forEach(id => {
        out.push('  <url>', '    <loc>' + esc(base + 'd/' + id + '.html') + '</loc>', '    <changefreq>monthly</changefreq>', '    <priority>0.5</priority>', '  </url>');
    });
    out.push('  ' + MARK_END);
    const block = out.join('\n');
    const re = new RegExp('[ \\t]*' + rx(MARK_START) + '[\\s\\S]*?' + rx(MARK_END) + '\\n?');
    if (re.test(xml)) return xml.replace(re, '  ' + block + '\n');
    const i = xml.lastIndexOf('</urlset>');
    if (i < 0) throw new Error('sitemap.xml has no </urlset>');
    return xml.slice(0, i) + '  ' + block + '\n' + xml.slice(i);
}

const meta = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'duas', 'metadata.json'), 'utf8'));
const want = {}; const problems = []; const seen = {};
TYPES.forEach(([key, type, label]) => {
    (meta[key] || []).forEach(it => {
        const id = it && it.id != null ? String(it.id) : '';
        if (!/^[A-Za-z0-9_-]{1,80}$/.test(id)) { problems.push('bad or missing id in ' + key + ': ' + JSON.stringify(id)); return; }
        if (seen[id]) { problems.push('duplicate id "' + id + '" (' + seen[id] + ' and ' + type + ')'); return; }
        seen[id] = type; want[id + '.html'] = pageFor(type, label, it);
    });
});
const ids = Object.keys(want).map(f => f.replace(/\.html$/, ''));
const sitemapNow = fs.readFileSync(SITEMAP, 'utf8');
const sitemapNew = withSitemapBlock(sitemapNow, ids);
if (sitemapNew !== sitemapNow) problems.push('sitemap.xml is out of date');
const existing = fs.existsSync(OUT_DIR) ? fs.readdirSync(OUT_DIR).filter(f => /\.html$/.test(f)) : [];
const stale = existing.filter(f => !(f in want));
stale.forEach(f => problems.push('stale page: d/' + f));
let changed = 0;
Object.keys(want).forEach(f => {
    const fp = path.join(OUT_DIR, f);
    const cur = fs.existsSync(fp) ? fs.readFileSync(fp, 'utf8') : null;
    if (cur !== want[f]) { changed++; problems.push((cur === null ? 'missing: d/' : 'outdated: d/') + f); }
});
const fatal = problems.filter(x => /^(bad|duplicate)/.test(x));
if (CHECK) {
    if (problems.length) {
        console.log('Dua share pages are NOT up to date (' + problems.length + ' issue(s)):');
        problems.slice(0, 15).forEach(x => console.log('  - ' + x));
        if (problems.length > 15) console.log('  … and ' + (problems.length - 15) + ' more');
        console.log('Run: node tools/build-dua-share-pages.js'); process.exit(1);
    }
    console.log('OK — ' + ids.length + ' share pages and the sitemap block are up to date.'); process.exit(0);
}
if (fatal.length) { fatal.forEach(x => console.error(x)); process.exit(2); }
fs.mkdirSync(OUT_DIR, { recursive: true });
Object.keys(want).forEach(f => fs.writeFileSync(path.join(OUT_DIR, f), want[f]));
stale.forEach(f => fs.unlinkSync(path.join(OUT_DIR, f)));
if (sitemapNew !== sitemapNow) fs.writeFileSync(SITEMAP, sitemapNew);
console.log('Base address : ' + base);
console.log('Share pages  : ' + ids.length + ' written (' + changed + ' new/changed), ' + stale.length + ' stale removed');
console.log('sitemap.xml  : ' + (sitemapNew !== sitemapNow ? 'updated' : 'already current'));
