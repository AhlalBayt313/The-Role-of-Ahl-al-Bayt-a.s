#!/usr/bin/env node
// =============================================================================
// build-share-pages.js  (v207)
// =============================================================================
// WHAT IT DOES
//   Reads data/blog-posts.json and writes one tiny static page per post to
//   p/<id>.html. Each page has that post's own Open Graph / Twitter tags (so a
//   Facebook / WhatsApp / Telegram link preview shows the right title and
//   excerpt instead of the generic site card) and sends a visitor straight to
//   the app:  ../?page=readPost&id=<id>
//   It also adds those pages to sitemap.xml (between two marker comments, so
//   re-running replaces the block instead of duplicating it).
//
// WHY
//   The app is a single-page app on a static host — every address serves the
//   same index.html with the same <meta> tags. These stubs are the only way
//   to give each post its own preview without a server.
//
// WHEN TO RUN  (no npm packages, Node only)
//   node tools/build-share-pages.js            write / refresh p/*.html + sitemap block
//   node tools/build-share-pages.js --check    change nothing; exit 1 if anything is out of date
//   node tools/build-share-pages.js --base=https://example.org/path/   different site address
//   Run it after adding or editing blog posts, then commit the p/ folder and
//   sitemap.xml together with data/blog-posts.json.
//
// NOTE  The og:url / og:image / sitemap addresses are absolute, so they need the
//   real site address (SITE_BASE below, or --base / the SITE_BASE environment
//   variable). If the site moves to a custom domain, re-run with the new base.
//   Only numeric ids get a page; admin-made (custom_…) posts do not exist in the
//   JSON file.
// =============================================================================
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DEFAULT_BASE = 'https://ahlalbayt313.github.io/The-Role-of-Ahl-al-Bayt-a.s/';
const SITE_NAME = 'আহলে বাইত (আ.) | Ahl al-Bayt (a.s)';
const OUT_DIR = path.join(ROOT, 'p');
const SITEMAP = path.join(ROOT, 'sitemap.xml');
const MARK_START = '<!-- share-pages:start (generated by tools/build-share-pages.js — do not edit) -->';
const MARK_END = '<!-- share-pages:end -->';

const args = process.argv.slice(2);
const CHECK = args.indexOf('--check') > -1;
let base = process.env.SITE_BASE || DEFAULT_BASE;
args.forEach(a => { if (a.indexOf('--base=') === 0) base = a.slice(7); });
if (!/^https?:\/\//.test(base)) { console.error('Base address must start with http:// or https://'); process.exit(2); }
if (base.slice(-1) !== '/') base += '/';

function esc(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}
function oneLine(s) { return String(s == null ? '' : s).replace(/\s+/g, ' ').trim(); }
function clip(s, n) { const a = Array.from(s); return a.length > n ? a.slice(0, n - 1).join('').trim() + '…' : s; }

function pageFor(p) {
    const id = String(p.id);
    const title = oneLine(p.titleBn) || oneLine(p.titleEn) || 'আহলে বাইত (আ.)';
    const desc = clip(oneLine(p.excerpt) || oneLine(p.contentBn).slice(0, 400) || oneLine(p.titleEn), 200);
    const url = base + 'p/' + id + '.html';
    const img = base + 'og-image.jpg';
    const target = '../?page=readPost&id=' + id;
    const lines = [
        '<!DOCTYPE html>',
        '<html lang="bn">',
        '<head>',
        '<meta charset="UTF-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<title>' + esc(title) + ' | আহলে বাইত (আ.)</title>',
        '<meta name="description" content="' + esc(desc) + '">',
        '<link rel="canonical" href="' + esc(url) + '">',
        '<link rel="icon" href="../favicon.ico">',
        '<meta property="og:type" content="article">',
        '<meta property="og:site_name" content="' + esc(SITE_NAME) + '">',
        '<meta property="og:title" content="' + esc(title) + '">',
        '<meta property="og:description" content="' + esc(desc) + '">',
        '<meta property="og:url" content="' + esc(url) + '">',
        '<meta property="og:image" content="' + esc(img) + '">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        '<meta property="og:locale" content="bn_BD">'
    ];
    if (/^\d{4}-\d{2}-\d{2}$/.test(String(p.date || ''))) lines.push('<meta property="article:published_time" content="' + esc(p.date) + '">');
    if (oneLine(p.category)) lines.push('<meta property="article:section" content="' + esc(oneLine(p.category)) + '">');
    lines.push(
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="' + esc(title) + '">',
        '<meta name="twitter:description" content="' + esc(desc) + '">',
        '<meta name="twitter:image" content="' + esc(img) + '">',
        '<meta http-equiv="refresh" content="0;url=' + esc(target) + '">',
        '<script>location.replace("' + target + '" + location.hash);</script>',
        '</head>',
        '<body>',
        '<article>',
        '<h1>' + esc(title) + '</h1>',
        '<p>' + esc(desc) + '</p>',
        '<p><a href="' + esc(target) + '">অ্যাপে পুরো লেখাটি পড়ুন →</a></p>',
        '</article>',
        '</body>',
        '</html>',
        ''
    );
    return lines.join('\n');
}

function sitemapBlock(posts) {
    const out = [MARK_START];
    posts.forEach(p => {
        out.push('  <url>');
        out.push('    <loc>' + esc(base + 'p/' + p.id + '.html') + '</loc>');
        if (/^\d{4}-\d{2}-\d{2}$/.test(String(p.date || ''))) out.push('    <lastmod>' + p.date + '</lastmod>');
        out.push('    <changefreq>monthly</changefreq>');
        out.push('    <priority>0.6</priority>');
        out.push('  </url>');
    });
    out.push('  ' + MARK_END);
    return out.join('\n');
}
function withSitemapBlock(xml, block) {
    const re = new RegExp('[ \\t]*' + MARK_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + MARK_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?');
    if (re.test(xml)) return xml.replace(re, '  ' + block + '\n');
    const i = xml.lastIndexOf('</urlset>');
    if (i < 0) throw new Error('sitemap.xml has no </urlset>');
    return xml.slice(0, i) + '  ' + block + '\n' + xml.slice(i);
}

// ---------------------------------------------------------------------------
const all = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'blog-posts.json'), 'utf8'));
if (!Array.isArray(all)) { console.error('data/blog-posts.json is not an array'); process.exit(2); }
const posts = all.filter(p => p && /^\d{1,6}$/.test(String(p.id)));
const skipped = all.length - posts.length;

const want = {};
posts.forEach(p => { want[p.id + '.html'] = pageFor(p); });

const problems = [];
let sitemapNow = fs.readFileSync(SITEMAP, 'utf8');
const sitemapNew = withSitemapBlock(sitemapNow, sitemapBlock(posts));
if (sitemapNew !== sitemapNow) problems.push('sitemap.xml is out of date');

const existing = fs.existsSync(OUT_DIR) ? fs.readdirSync(OUT_DIR).filter(f => /^\d+\.html$/.test(f)) : [];
const stale = existing.filter(f => !(f in want));
stale.forEach(f => problems.push('stale page: p/' + f));
let changed = 0;
Object.keys(want).forEach(f => {
    const fp = path.join(OUT_DIR, f);
    const cur = fs.existsSync(fp) ? fs.readFileSync(fp, 'utf8') : null;
    if (cur !== want[f]) { changed++; problems.push((cur === null ? 'missing: p/' : 'outdated: p/') + f); }
});

if (CHECK) {
    if (problems.length) {
        console.log('Share pages are NOT up to date (' + problems.length + ' issue(s)):');
        problems.slice(0, 15).forEach(x => console.log('  - ' + x));
        if (problems.length > 15) console.log('  … and ' + (problems.length - 15) + ' more');
        console.log('Run: node tools/build-share-pages.js');
        process.exit(1);
    }
    console.log('OK — ' + posts.length + ' share pages and the sitemap block are up to date.');
    process.exit(0);
}

fs.mkdirSync(OUT_DIR, { recursive: true });
Object.keys(want).forEach(f => { fs.writeFileSync(path.join(OUT_DIR, f), want[f]); });
stale.forEach(f => fs.unlinkSync(path.join(OUT_DIR, f)));
if (sitemapNew !== sitemapNow) fs.writeFileSync(SITEMAP, sitemapNew);
console.log('Base address : ' + base);
console.log('Share pages  : ' + posts.length + ' written (' + changed + ' new/changed), ' + stale.length + ' stale removed' + (skipped ? ', ' + skipped + ' non-numeric id(s) skipped' : ''));
console.log('sitemap.xml  : ' + (sitemapNew !== sitemapNow ? 'updated' : 'already current'));
